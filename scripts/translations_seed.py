SERVING = re.compile(r"^(?P<n>[\d./]+) (?P<unit>[a-z ]+?)(?: (?P<metric>\(.*\)))?$")


def serving(text):
    m = SERVING.match(text)
    if not m or m.group("unit") not in UNITS:
        return None
    n, unit, metric = m.group("n"), m.group("unit"), m.group("metric") or ""
    es1, esn, de1, den = UNITS[unit]
    plural = n not in ("1", "1/2", "1/4")
    decimal = n.replace(".", ",")
    metric_es = metric.replace("nuts", "unidades")
    metric_de = metric.replace("nuts", "Stück")
    if unit == "fl oz can":
        return (f"lata de {n} fl oz {metric}".strip(), f"{decimal}-fl-oz-Dose {metric}".strip())
    es = f"{decimal} {esn if plural else es1} {metric_es}".strip()
    de = f"{decimal} {den if plural else de1} {metric_de}".strip()
    return es, de


